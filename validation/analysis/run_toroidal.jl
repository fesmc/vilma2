#!/usr/bin/env julia
#
# run_toroidal.jl — V7: the production 3-D deglaciation with the toroidal field
# of the 3-D elements carried (`D-V2-3D.l170.tor`) against the same run without
# it (`D-V2-3D.l170.fe`, the control: same model head, reference, namelist but
# for `l_toroidal`). Writes tables/toroidal.md; reads data/published/ only.
#
#   julia --project=. analysis/run_toroidal.jl

using CairoMakie
using Printf
using Statistics

include(joinpath(@__DIR__, "Published.jl"))
include(joinpath(@__DIR__, "FigStyle.jl"))
using .Published
using .FigStyle

const TOR, CTL, V1 = "D-V2-3D.l170.tor", "D-V2-3D.l170.fe", "D-V1-3D.l170.fe"
const T = [-21000.0, -10000.0, 0.0]

tr, ct, v1 = load_run(TOR), load_run(CTL), load_run(V1)
(tr === nothing || ct === nothing) && error("V7 needs $TOR and $CTL in data/published/blockD")

W  = repeat(reshape(lat_weights(ct.lat), 1, :), length(ct.lon), 1) ./ length(ct.lon)
wrms(f) = sqrt(sum(W .* f .^ 2))
wall_per_kyr(r) = haskey(r.ds.attrib, "elapsed_s") ?
    Float64(r.ds.attrib["elapsed_s"]) / 60 / ((r.time[end] - r.time[1]) / 1000) : NaN

io = IOBuffer()
println(io, "# V7 — the toroidal field in the 3-D deglaciation\n")
println(io, "Generated by `analysis/run_toroidal.jl` from `data/published/blockD/`. ",
            "`$TOR` carries the toroidal field of the laterally 3-D elements ",
            "(`l_toroidal = .true.`); `$CTL` is the same run without it (same model ",
            "head, LGM reference, ℓmax 170 and namelist but for that key). rms is area-weighted.\n")

println(io, "## Relative sea level, tor − control\n")
println(io, "Relative sea level against the LGM reference state (not against each run's present day).\n")
println(io, "| time | rms [m] | max\\|Δ\\| [m] | control signal max\\|rsl\\| [m] |")
println(io, "|---|---:|---:|---:|")
for t in T
    d = slice_at(tr, "rsl", t) .- slice_at(ct, "rsl", t)
    @printf(io, "| %.0f ka | %.4f | %.3f | %.1f |\n", ka(t), wrms(d), maximum(abs.(d)),
            maximum(abs.(slice_at(ct, "rsl", t))))
    record!("v7", "tor_minus_ctl_rsl_rms_$(round(Int, ka(t)))ka_m" => round(wrms(d), digits = 4),
                  "tor_minus_ctl_rsl_max_$(round(Int, ka(t)))ka_m" => round(maximum(abs.(d)), digits = 3))
end
du = uplift_rate(tr) .- uplift_rate(ct)
@printf(io, "\nPresent-day uplift rate, tor − control: rms %.4f mm/yr, max %.3f mm/yr.\n",
        wrms(du), maximum(abs.(du)))

bt, bc = budget_at(tr), budget_at(ct)
println(io, "\n## Global numbers\n")
println(io, "| quantity | control | tor | tor − control |")
println(io, "|---|---:|---:|---:|")
omt, omc = ocean_mean(tr, 0.0), ocean_mean(ct, 0.0)
@printf(io, "| ocean-mean rsl at present day [m] | %.3f | %.3f | %+.3f |\n", omc, omt, omt - omc)
@printf(io, "| budget closure, delivered/target [%%] | %.2f | %.2f | %+.2f |\n",
        100bc.closure, 100bt.closure, 100(bt.closure - bc.closure))
if v1 !== nothing
    for t in (-21000.0, -10000.0)
        rc = wrms(rsl_anomaly(ct, t) .- rsl_anomaly(v1, t))
        rt = wrms(rsl_anomaly(tr, t) .- rsl_anomaly(v1, t))
        @printf(io, "| V2 − V1 (3-D) rms of rsl at %.0f ka [m] | %.3f | %.3f | %+.3f |\n", ka(t), rc, rt, rt - rc)
    end
    uc = wrms(uplift_rate(ct) .- uplift_rate(v1)); ut = wrms(uplift_rate(tr) .- uplift_rate(v1))
    @printf(io, "| V2 − V1 (3-D) rms of present-day uplift rate [mm/yr] | %.4f | %.4f | %+.4f |\n", uc, ut, ut - uc)
end
wc, wt = wall_per_kyr(ct), wall_per_kyr(tr)
@printf(io, "| wall time per kyr of deglaciation [min] | %.2f | %.2f | ×%.2f |\n", wc, wt, wt / wc)
println(io, "\nWall times from the jobs' own accounting (64 threads on a shared albedo node); ",
            "V2 − V1 uses rsl relative to each run's present day, as in `v2v1.md`.")
record!("v7", "ocean_mean_pd_ctl_m" => round(omc, digits = 3), "ocean_mean_pd_tor_m" => round(omt, digits = 3),
              "closure_ctl_pct" => round(100bc.closure, digits = 2), "closure_tor_pct" => round(100bt.closure, digits = 2),
              "wall_per_kyr_ctl_min" => round(wc, digits = 2), "wall_per_kyr_tor_min" => round(wt, digits = 2))

# ------------------------------------------------------------------ map, 10 ka
d10 = slice_at(tr, "rsl", -10000.0) .- slice_at(ct, "rsl", -10000.0)
lim = symlim(d10; q = 0.999)
fig = Figure(size = (1000, 520))
ax = Axis(fig[1, 1]; aspect = DataAspect(), xlabel = "longitude [deg]", ylabel = "latitude [deg]",
          xticks = -180:60:180, yticks = -90:30:90)
hm = heatmap!(ax, tr.lon, tr.lat, d10; colormap = CMAP_DIV, colorrange = lim)
contour!(ax, ct.lon, ct.lat, slice_at(ct, "h_ice", -10000.0); levels = [10.0],
         color = :black, linewidth = 0.8)
limits!(ax, -180, 180, -90, 90)
Colorbar(fig[1, 2], hm; label = "Δ relative sea level, toroidal − control [m]")
savefig(fig, "toroidal-10ka";
    title = "Effect of the toroidal field at 10 ka",
    caption = """
    Relative sea level at 10 ka in the 3-D deglaciation with the toroidal field of the
    laterally 3-D elements carried, minus the same run without it (`D-V2-3D.l170.tor`
    minus `D-V2-3D.l170.fe`, ℓmax 170, both against the same LGM reference state).
    The black line is the ice margin of the control at 10 ka (10 m thickness). The
    colour range is the 99.9th percentile of |Δ|.
    """,
    notes = """
    Numbers in `tables/toroidal.md`: area-weighted rms $(@sprintf("%.2f", wrms(d10))) m,
    max $(@sprintf("%.1f", maximum(abs.(d10)))) m at 10 ka.
    """,
    source = @__FILE__,
    runs = [tr.path, ct.path])

path = joinpath(tables_dir(), "toroidal.md")
write(path, String(take!(io)))
@info "wrote $path"
